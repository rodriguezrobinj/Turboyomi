// Tests against the real embedded browser (spec 2b §5). It's downloaded once into build/cef at the repo's root
val cefTest by tasks.registering(Test::class) {
    description = "Runs the tests that need the real embedded browser"
    group = "verification"
    testClassesDirs = sourceSets.test.get().output.classesDirs
    classpath = sourceSets.test.get().runtimeClasspath
    forkEvery = 1
    useJUnitPlatform { includeTags("cef") }
    systemProperty("cef.dir", layout.settingsDirectory.dir("build/cef").asFile.absolutePath)
    // JCEF's windowed browser reaches into AWT's internals; JetBrains Runtime opens them, other JDKs need this
    jvmArgs("--add-exports=java.desktop/sun.awt=ALL-UNNAMED", "--add-exports=java.desktop/sun.awt.windows=ALL-UNNAMED")
}

// DesktopBuildInfo from git (spec 6a §2): the version of the last v* tag (Mihon's upstream-base tag doesn't count),
// 0.1.0 without one; the code orders versions
val gitTag = providers.exec {
    commandLine("git", "describe", "--tags", "--match", "v*", "--abbrev=0")
    isIgnoreExitValue = true
}.standardOutput.asText.map { it.trim() }
val gitCommit = providers.exec {
    commandLine("git", "rev-parse", "--short", "HEAD")
    isIgnoreExitValue = true
}.standardOutput.asText.map { it.trim().ifEmpty { "unknown" } }

val generateBuildInfo by tasks.registering {
    val out = layout.buildDirectory.dir("generated/buildinfo")
    val tag = gitTag
    val commit = gitCommit
    inputs.property("tag", tag)
    inputs.property("commit", commit)
    outputs.dir(out)
    doLast {
        val version = Regex("""^v(\d+)\.(\d+)\.(\d+)$""").find(tag.get())?.groupValues?.drop(1)
            ?.map(String::toInt) ?: listOf(0, 1, 0)
        val file = out.get().file("mihon/desktop/core/DesktopBuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package mihon.desktop.core
            |
            |/** Generated by :desktop-core:generateBuildInfo from git (spec 6a §2). */
            |object DesktopBuildInfo {
            |    const val VERSION_NAME = "${version.joinToString(".")}"
            |    const val VERSION_CODE = ${version[0] * 10_000 + version[1] * 100 + version[2]}
            |    // Not const: a new commit then doesn't change the ABI that every module compiles against
            |    val COMMIT_SHA = "${commit.get()}"
            |
            |    /** Names the default shared preferences file. */
            |    const val APPLICATION_ID = "app.turboyomi"
            |}
            |
            """.trimMargin(),
        )
    }
}
kotlin.sourceSets.main { kotlin.srcDir(generateBuildInfo) }
